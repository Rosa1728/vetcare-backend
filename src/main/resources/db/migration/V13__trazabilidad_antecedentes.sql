ALTER TABLE historia_clinica ADD COLUMN version_antecedentes BIGINT NOT NULL DEFAULT 0;
CREATE TABLE antecedente_cambio (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_historia BIGINT NOT NULL REFERENCES historia_clinica(id_historia),
 seccion VARCHAR(20) NOT NULL CHECK (seccion IN ('alergias','medicos','cirugias','cuidados')),
 anterior JSONB NOT NULL, nuevo JSONB NOT NULL,
 id_veterinario BIGINT NOT NULL REFERENCES veterinario(id_veterinario),
 nombre_veterinario VARCHAR(201) NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL,
 motivo VARCHAR(500), id_atencion BIGINT REFERENCES atenciones(id_atencion),
 revision BIGINT NOT NULL CHECK (revision>0),
 CONSTRAINT uq_antecedente_revision_seccion UNIQUE(id_historia,revision,seccion)
);
CREATE INDEX idx_antecedente_historia_revision ON antecedente_cambio(id_historia,revision DESC,id DESC);
CREATE FUNCTION impedir_modificacion_antecedente_cambio() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Los cambios de antecedentes son inmutables; registre una nueva corrección'; END;
$$;
CREATE TRIGGER antecedente_cambio_inmutable BEFORE UPDATE OR DELETE ON antecedente_cambio
FOR EACH ROW EXECUTE FUNCTION impedir_modificacion_antecedente_cambio();
