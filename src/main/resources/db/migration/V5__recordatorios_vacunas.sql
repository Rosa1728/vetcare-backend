CREATE TABLE recordatorio_vacuna (
    id_recordatorio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vacuna BIGINT NOT NULL REFERENCES vacuna(id_vacuna),
    fecha_dosis DATE NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    leido_en TIMESTAMP,
    CONSTRAINT uq_recordatorio_dosis_tipo UNIQUE (id_vacuna, fecha_dosis, tipo),
    CONSTRAINT ck_recordatorio_tipo CHECK (tipo IN ('DIA_7', 'DIA_1', 'HOY', 'VENCIDA'))
);
CREATE INDEX idx_recordatorio_vacuna ON recordatorio_vacuna(id_vacuna);
