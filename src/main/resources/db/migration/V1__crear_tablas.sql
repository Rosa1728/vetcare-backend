-- VetCare: esquema inicial según entidades JPA compartidas (PostgreSQL)
CREATE TABLE roles (
                       id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       nombre VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE usuario (
                         id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombres VARCHAR(100) NOT NULL,
                         apellidos VARCHAR(100) NOT NULL,
                         tipo_documento VARCHAR(20) NOT NULL,
                         nro_documento VARCHAR(20) NOT NULL UNIQUE,
                         correo VARCHAR(150) NOT NULL UNIQUE,
                         contrasena VARCHAR(255) NOT NULL,
                         nro_celular VARCHAR(20),
                         id_rol BIGINT NOT NULL REFERENCES roles(id_rol),
                         fecha_registro TIMESTAMP(6) NOT NULL
);

CREATE TABLE propietario (
                             id_propietario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuario(id_usuario),
                             direccion VARCHAR(200),
                             fecha_registro_clinica DATE NOT NULL,
                             estado_cliente VARCHAR(20) NOT NULL
);

CREATE TABLE veterinario (
                             id_veterinario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuario(id_usuario),
                             especialidad VARCHAR(255),
                             nro_colegiatura VARCHAR(255)
);

CREATE TABLE mascota (
                         id_mascota BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         id_propietario BIGINT NOT NULL REFERENCES propietario(id_propietario),
                         nombre VARCHAR(100) NOT NULL,
                         especie VARCHAR(50) NOT NULL,
                         raza VARCHAR(100),
                         sexo VARCHAR(10),
                         fecha_nacimiento DATE
);

CREATE TABLE historia_clinica (
                                  id_historia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  id_mascota BIGINT NOT NULL UNIQUE REFERENCES mascota(id_mascota),
                                  fecha_apertura TIMESTAMP(6) NOT NULL
);

CREATE TABLE cita (
                      id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      id_veterinario BIGINT NOT NULL REFERENCES veterinario(id_veterinario),
                      id_mascota BIGINT NOT NULL REFERENCES mascota(id_mascota),
                      fecha_cita TIMESTAMP(6) NOT NULL,
                      estado VARCHAR(255) NOT NULL,
                      motivo_cita VARCHAR(255)
);

CREATE TABLE atenciones (
                            id_atencion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            id_historia BIGINT NOT NULL REFERENCES historia_clinica(id_historia),
                            id_veterinario_atencion BIGINT NOT NULL REFERENCES veterinario(id_veterinario),
                            id_cita BIGINT NOT NULL UNIQUE REFERENCES cita(id_cita),
                            fecha_atencion TIMESTAMP(6) NOT NULL,
                            precio_atencion NUMERIC(38,2),
                            peso NUMERIC(38,2),
                            sintoma VARCHAR(255),
                            diagnostico VARCHAR(255),
                            tratamiento VARCHAR(255),
                            observacion VARCHAR(255)
);
