CREATE TABLE regularizacion_atencion (
 id_regularizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cita BIGINT NOT NULL REFERENCES cita(id_cita),
 id_veterinario BIGINT NOT NULL REFERENCES veterinario(id_veterinario),
 motivo VARCHAR(500) NOT NULL,
 fecha_solicitud TIMESTAMP(6) NOT NULL,
 estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA','CONSUMIDA','EXPIRADA')),
 id_administrador BIGINT REFERENCES usuario(id_usuario),
 fecha_resolucion TIMESTAMP(6),
 vence_en TIMESTAMP(6),
 consumida_en TIMESTAMP(6)
);
CREATE UNIQUE INDEX uq_regularizacion_activa ON regularizacion_atencion(id_cita) WHERE estado IN ('PENDIENTE','APROBADA');
CREATE INDEX idx_regularizacion_veterinario ON regularizacion_atencion(id_veterinario);
