CREATE TABLE vacuna (
    id_vacuna BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mascota BIGINT NOT NULL REFERENCES mascota(id_mascota),
    id_veterinario BIGINT NOT NULL REFERENCES veterinario(id_veterinario),
    id_atencion BIGINT REFERENCES atenciones(id_atencion),
    nombre VARCHAR(120) NOT NULL,
    fecha_aplicacion DATE,
    proxima_dosis DATE,
    observaciones VARCHAR(500),
    CONSTRAINT ck_vacuna_fechas CHECK (
        (fecha_aplicacion IS NOT NULL AND id_atencion IS NOT NULL)
        OR (fecha_aplicacion IS NULL AND id_atencion IS NULL AND proxima_dosis IS NOT NULL)
    ),
    CONSTRAINT ck_vacuna_orden_dosis CHECK (
        proxima_dosis IS NULL OR fecha_aplicacion IS NULL OR proxima_dosis > fecha_aplicacion
    )
);
CREATE INDEX idx_vacuna_mascota ON vacuna(id_mascota);
CREATE INDEX idx_vacuna_proxima_dosis ON vacuna(proxima_dosis);
