CREATE TABLE recuperacion_contrasena (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 correo VARCHAR(150) NOT NULL,
 id_usuario BIGINT REFERENCES usuario(id_usuario),
 token_hash VARCHAR(64) UNIQUE,
 creado_en TIMESTAMPTZ NOT NULL,
 vence_en TIMESTAMPTZ,
 usado_en TIMESTAMPTZ,
 estado VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','PROCESADA','ERROR')),
 intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0 AND intentos <= 3)
);
CREATE INDEX idx_recuperacion_pendiente ON recuperacion_contrasena(estado,creado_en);
CREATE INDEX idx_recuperacion_correo ON recuperacion_contrasena(correo,creado_en);
CREATE INDEX idx_recuperacion_usuario ON recuperacion_contrasena(id_usuario);
